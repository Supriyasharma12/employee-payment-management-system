
-- ============================================================
-- V20: Payment Advice numbering and finalization
--
-- One advice per bank per payment batch.
-- Organisation-wide monthly reference sequence.
-- Cancelled advice numbers are never reused.
-- ============================================================

-- 1. Monthly organisation-wide sequence.
CREATE TABLE payment_advice_sequence (
                                         sequence_year INTEGER NOT NULL,
                                         sequence_month INTEGER NOT NULL,
                                         last_number INTEGER NOT NULL DEFAULT 0,

                                         CONSTRAINT pk_payment_advice_sequence
                                             PRIMARY KEY (sequence_year, sequence_month),

                                         CONSTRAINT chk_payment_advice_sequence_month
                                             CHECK (sequence_month BETWEEN 1 AND 12),

                                         CONSTRAINT chk_payment_advice_sequence_number
                                             CHECK (last_number >= 0)
);


-- 2. Finalized Payment Advice records.
CREATE TABLE payment_advice (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                reference_no VARCHAR(30) NOT NULL,

                                payment_batch_id BIGINT NOT NULL,
                                bank_id BIGINT NOT NULL,

                                advice_date DATE NOT NULL,

                                status VARCHAR(20) NOT NULL DEFAULT 'FINALIZED',

                                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                cancelled_at TIMESTAMP NULL,
                                cancellation_reason VARCHAR(500) NULL,

                                CONSTRAINT uk_payment_advice_reference
                                    UNIQUE (reference_no),

                                CONSTRAINT fk_payment_advice_batch
                                    FOREIGN KEY (payment_batch_id)
                                        REFERENCES payment_batches(id),

                                CONSTRAINT fk_payment_advice_bank
                                    FOREIGN KEY (bank_id)
                                        REFERENCES banks(id),

                                CONSTRAINT chk_payment_advice_status
                                    CHECK (status IN ('FINALIZED', 'CANCELLED')),

                                CONSTRAINT chk_payment_advice_cancellation
                                    CHECK (
                                        (status = 'FINALIZED'
                                            AND cancelled_at IS NULL
                                            AND cancellation_reason IS NULL)
                                            OR
                                        (status = 'CANCELLED'
                                            AND cancelled_at IS NOT NULL
                                            AND cancellation_reason IS NOT NULL
                                            AND LENGTH(TRIM(cancellation_reason)) > 0)
                                        )
);


-- 3. Prevent two active advices for the same bank and batch.
-- Cancelled advice records remain permanently stored.
CREATE UNIQUE INDEX uk_payment_advice_active_batch_bank
    ON payment_advice(payment_batch_id, bank_id)
    WHERE status = 'FINALIZED';


-- 4. Store the exact payment IDs included in each advice.
CREATE TABLE payment_advice_payments (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                         payment_advice_id BIGINT NOT NULL,
                                         payment_id BIGINT NOT NULL,

                                         CONSTRAINT fk_payment_advice_payments_advice
                                             FOREIGN KEY (payment_advice_id)
                                                 REFERENCES payment_advice(id),

                                         CONSTRAINT fk_payment_advice_payments_payment
                                             FOREIGN KEY (payment_id)
                                                 REFERENCES payments(id),

                                         CONSTRAINT uk_payment_advice_payment
                                             UNIQUE (payment_advice_id, payment_id)
);


-- 5. Indexes for advice history and payment lookup.
CREATE INDEX idx_payment_advice_batch
    ON payment_advice(payment_batch_id);

CREATE INDEX idx_payment_advice_bank
    ON payment_advice(bank_id);

CREATE INDEX idx_payment_advice_date
    ON payment_advice(advice_date);

CREATE INDEX idx_payment_advice_payment_id
    ON payment_advice_payments(payment_id);
